def _generate_prisma_png(counts: PrismaCounts, path: Path, title: str):
    """Generate PRISMA flow diagram as PNG using matplotlib."""
    try:
        import matplotlib
        matplotlib.use('Agg')
        import matplotlib.pyplot as plt
        import matplotlib.patches as patches
    except ImportError:
        raise ImportError("matplotlib required for PNG export. Install with: pip install matplotlib")

    path.parent.mkdir(parents=True, exist_ok=True)

    fig, ax = plt.subplots(1, 1, figsize=(10, 12))
    ax.set_xlim(0, 10)
    ax.set_ylim(0, 14)
    ax.axis('off')

    total_identified = sum(counts.records_identified.values()) if counts.records_identified else counts.records_before_dedup

    boxes = [
        (1, 12.5, 8, 1.2, "Identification", f"Records identified: {total_identified}", [
            f"{source}: {count}" for source, count in counts.records_identified.items()
        ]),
        (1, 10.5, 8, 1.5, "Deduplication", "", [
            f"Records before dedup: {counts.records_before_dedup}",
            f"Duplicates removed: {counts.duplicates_removed}",
            f"Records after dedup: {counts.records_after_dedup}",
        ]),
        (1, 8.2, 8, 1.8, "Screening", "", [
            f"Records screened: {counts.records_screened}",
            f"Excluded (automatic): {counts.records_excluded_automatic}",
            f"Excluded (manual): {counts.records_excluded_manual}",
            f"Conflicts: {counts.records_conflicts}",
        ]),
        (1, 5.5, 8, 1.2, "Included", f"Records included: {counts.records_included}", []),
    ]

    for i, (x, y, w, h, label, count, details) in enumerate(boxes):
        color = '#e8f5e9' if i == len(boxes) - 1 else '#f5f5f5'
        rect = patches.FancyBboxPatch((x, y), w, h, boxstyle="round,pad=0.1", facecolor=color, edgecolor='#333', linewidth=2)
        ax.add_patch(rect)

        ax.text(x + w/2, y + h - 0.3, label, ha='center', va='top', fontsize=14, fontweight='bold')
        if count:
            ax.text(x + w/2, y + h - 0.6, count, ha='center', va='top', fontsize=16, fontweight='bold', color='#2c5f8a')
        for j, detail in enumerate(details):
            ax.text(x + w/2, y + h - 0.9 - j*0.3, detail, ha='center', va='top', fontsize=12)

        if i < len(boxes) - 1:
            next_y = boxes[i+1][1]
            ax.annotate('', xy=(x + w/2, y), xytext=(x + w/2, next_y + boxes[i+1][3]),
                       arrowprops=dict(arrowstyle='->', lw=2, color='#333'))

    ax.text(5, 0.5, f"Generated by LITHOS v{VERSION} on {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}", ha='center', fontsize=10, color='#666')

    plt.tight_layout()
    plt.savefig(path, dpi=300, bbox_inches='tight')
    plt.close()


def generate_search_report(
    records: list[Record],
    manifest: RunManifest,
    output_path: Path,
    format: str = "md",
) -> None:
    """Generate a search report ready for Methods section."""
    output_path.parent.mkdir(parents=True, exist_ok=True)

    if format == "md":
        _generate_search_report_md(records, manifest, output_path)
    elif format == "docx":
        _generate_search_report_docx(records, manifest, output_path)
    else:
        raise ValueError(f"Unsupported format: {format}")


def _generate_search_report_md(records: list[Record], manifest: RunManifest, path: Path):
    """Generate search report as Markdown."""
    lines = [
        f"# Search Report for Scoping Review\n",
        f"**Generated by LITHOS v{VERSION}** on {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}\n",
        f"Run ID: {manifest.run_id}\n",
        f"LITHOS Version: {manifest.lithos_version}\n",
        f"\n## Search Strategy\n",
    ]

    # Queries
    lines.append("### Search Queries\n")
    for i, q in enumerate(manifest.queries, 1):
        lines.append(f"**Query {i}**: {q.original}")
        if q.boolean_query != q.original:
            lines.append(f"  - Boolean translation: {q.boolean_query}")
        if q.filters:
            lines.append(f"  - Filters: {q.filters}")
        lines.append("")

    # Sources
    lines.append("### Information Sources\n")
    for source in manifest.sources_used:
        lines.append(f"- {source}")
    lines.append("")

    # Date
    lines.append(f"### Search Date\n")
    lines.append(f"Search conducted: {manifest.started_at}\n")

    # Results
    lines.append("## Search Results\n")
    lines.append(f"- Total records identified: {manifest.total_records_found}")
    lines.append(f"- Records after deduplication: {manifest.total_records_after_dedup}")
    lines.append("")

    # Validation summary
    lines.append("## Validation Summary\n")
    for status, count in manifest.validation_summary.items():
        lines.append(f"- {status}: {count}")
    lines.append("")

    # PRISMA flow reference
    lines.append("## PRISMA Flow Diagram\n")
    lines.append("See separate PRISMA flow diagram file (prisma_flow.svg).\n")

    # Evidence maps
    lines.append("## Evidence Maps\n")
    lines.append("### By Publication Year\n")
    year_counts = Counter(r.year for r in records if r.year)
    for year in sorted(year_counts.keys()):
        lines.append(f"- {year}: {year_counts[year]}")
    lines.append("")

    lines.append("### By Venue (Top 20)\n")
    venue_counts = Counter(r.venue for r in records if r.venue)
    for venue, count in venue_counts.most_common(20):
        lines.append(f"- {venue}: {count}")
    lines.append("")

    lines.append("### By Country (from affiliations - if available)\n")
    lines.append("*Country analysis requires affiliation data not always available.*\n")

    lines.append("### By Topic (Keyword Co-occurrence)\n")
    kw_counts = Counter()
    for r in records:
        for kw in r.keywords:
            kw_counts[kw.lower()] += 1
    for kw, count in kw_counts.most_common(20):
        lines.append(f"- {kw}: {count}")
    lines.append("")

    path.write_text("\n".join(lines))


def _generate_search_report_docx(records: list[Record], manifest: RunManifest, path: Path):
    """Generate search report as DOCX (requires python-docx)."""
    try:
        from docx import Document
        from docx.shared import Inches, Pt
        from docx.enum.text import WD_ALIGN_PARAGRAPH
    except ImportError:
        raise ImportError("python-docx required for DOCX export. Install with: pip install python-docx")

    path.parent.mkdir(parents=True, exist_ok=True)
    doc = Document()

    # Title
    title = doc.add_heading('Search Report for Scoping Review', 0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER

    # Metadata
    p = doc.add_paragraph()
    p.add_run(f"Generated by LITHOS v{VERSION} on {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}\n").italic = True
    p.add_run(f"Run ID: {manifest.run_id}\n")
    p.add_run(f"LITHOS Version: {manifest.lithos_version}\n")

    # Search Strategy
    doc.add_heading('Search Strategy', level=1)

    doc.add_heading('Search Queries', level=2)
    for i, q in enumerate(manifest.queries, 1):
        p = doc.add_paragraph()
        p.add_run(f'Query {i}: ').bold = True
        p.add_run(q.original)
        if q.boolean_query != q.original:
            doc.add_paragraph(f"Boolean translation: {q.boolean_query}", style='List Bullet')
        if q.filters:
            doc.add_paragraph(f"Filters: {q.filters}", style='List Bullet')

    doc.add_heading('Information Sources', level=2)
    for source in manifest.sources_used:
        doc.add_paragraph(source, style='List Bullet')

    doc.add_heading('Search Date', level=2)
    doc.add_paragraph(manifest.started_at)

    # Results
    doc.add_heading('Search Results', level=1)
    doc.add_paragraph(f"Total records identified: {manifest.total_records_found}")
    doc.add_paragraph(f"Records after deduplication: {manifest.total_records_after_dedup}")

    # Validation
    doc.add_heading('Validation Summary', level=2)
    for status, count in manifest.validation_summary.items():
        doc.add_paragraph(f"{status}: {count}", style='List Bullet')

    # Evidence Maps
    doc.add_heading('Evidence Maps', level=1)

    doc.add_heading('By Publication Year', level=2)
    year_counts = Counter(r.year for r in records if r.year)
    table = doc.add_table(rows=1, cols=2)
    table.style = 'Light Shading Accent 1'
    hdr = table.rows[0].cells
    hdr[0].text = 'Year'
    hdr[1].text = 'Count'
    for year in sorted(year_counts.keys()):
        row = table.add_row().cells
        row[0].text = str(year)
        row[1].text = str(year_counts[year])

    doc.add_heading('By Venue (Top 20)', level=2)
    venue_counts = Counter(r.venue for r in records if r.venue)
    table = doc.add_table(rows=1, cols=2)
    table.style = 'Light Shading Accent 1'
    hdr = table.rows[0].cells
    hdr[0].text = 'Venue'
    hdr[1].text = 'Count'
    for venue, count in venue_counts.most_common(20):
        row = table.add_row().cells
        row[0].text = venue
        row[1].text = str(count)

    doc.add_heading('By Topic (Keyword Co-occurrence, Top 20)', level=2)
    kw_counts = Counter()
    for r in records:
        for kw in r.keywords:
            kw_counts[kw.lower()] += 1
    table = doc.add_table(rows=1, cols=2)
    table.style = 'Light Shading Accent 1'
    hdr = table.rows[0].cells
    hdr[0].text = 'Keyword'
    hdr[1].text = 'Count'
    for kw, count in kw_counts.most_common(20):
        row = table.add_row().cells
        row[0].text = kw
        row[1].text = str(count)

    doc.save(path)


def generate_evidence_maps(records: list[Record], output_dir: Path) -> dict[str, Path]:
    """Generate evidence map tables as CSV files."""
    output_dir.mkdir(parents=True, exist_ok=True)
    paths = {}

    # By year
    year_counts = Counter(r.year for r in records if r.year)
    year_path = output_dir / "evidence_map_by_year.csv"
    with year_path.open("w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["year", "count"])
        for year in sorted(year_counts.keys()):
            writer.writerow([year, year_counts[year]])
    paths["by_year"] = year_path

    # By venue
    venue_counts = Counter(r.venue for r in records if r.venue)
    venue_path = output_dir / "evidence_map_by_venue.csv"
    with venue_path.open("w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["venue", "count"])
        for venue, count in venue_counts.most_common():
            writer.writerow([venue, count])
    paths["by_venue"] = venue_path

    # By keyword
    kw_counts = Counter()
    for r in records:
        for kw in r.keywords:
            kw_counts[kw.lower()] += 1
    kw_path = output_dir / "evidence_map_by_keyword.csv"
    with kw_path.open("w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["keyword", "count"])
        for kw, count in kw_counts.most_common():
            writer.writerow([kw, count])
    paths["by_keyword"] = kw_path

    # By publication type
    type_counts = Counter(r.publication_type for r in records if r.publication_type)
    type_path = output_dir / "evidence_map_by_type.csv"
    with type_path.open("w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["publication_type", "count"])
        for ptype, count in type_counts.most_common():
            writer.writerow([ptype, count])
    paths["by_type"] = type_path

    # By source
    source_counts = Counter(r.source for r in records)
    source_path = output_dir / "evidence_map_by_source.csv"
    with source_path.open("w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["source", "count"])
        for source, count in source_counts.most_common():
            writer.writerow([source, count])
    paths["by_source"] = source_path

    return paths