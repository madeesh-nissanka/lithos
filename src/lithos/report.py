@dataclass
class PrismaCounts:
    """Counts for PRISMA flow diagram."""
    records_identified: dict[str, int] = None  # per source
    records_before_dedup: int = 0
    duplicates_removed: int = 0
    records_after_dedup: int = 0
    records_screened: int = 0
    records_excluded_automatic: int = 0
    records_excluded_manual: int = 0
    records_included: int = 0
    records_conflicts: int = 0

    def __post_init__(self):
        if self.records_identified is None:
            self.records_identified = {}


def generate_prisma_flow(
    records: list[Record],
    counts: PrismaCounts,
    output_path: Path,
    format: str = "svg",
    title: str = "PRISMA 2020 Flow Diagram",
) -> None:
    """Generate PRISMA flow diagram as SVG or PNG (via matplotlib if available)."""
    if format == "svg":
        _generate_prisma_svg(counts, output_path, title)
    elif format == "png":
        _generate_prisma_png(counts, output_path, title)
    else:
        raise ValueError(f"Unsupported format: {format}")


